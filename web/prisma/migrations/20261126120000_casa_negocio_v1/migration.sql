-- ---------------------------------------------------------------------------
-- 3. CHECK constraints (hand-written; Prisma cannot express them)
-- ---------------------------------------------------------------------------

ALTER TABLE "cn_cuentas"
  ADD CONSTRAINT "cn_cuentas_archivada_coherente"
    CHECK (("archivada" AND "archivadaEn" IS NOT NULL) OR (NOT "archivada" AND "archivadaEn" IS NULL));

ALTER TABLE "cn_categorias_gasto"
  ADD CONSTRAINT "cn_categorias_gasto_monto_no_negativo" CHECK ("monto" IS NULL OR "monto" >= 0),
  ADD CONSTRAINT "cn_categorias_gasto_dia_valido" CHECK ("diaPago" IS NULL OR "diaPago" BETWEEN 1 AND 31),
  ADD CONSTRAINT "cn_categorias_gasto_mes_valido" CHECK ("mesAnual" IS NULL OR "mesAnual" BETWEEN 1 AND 12),
  -- An annual expense must say in which month it is due; a monthly one must not.
  ADD CONSTRAINT "cn_categorias_gasto_mes_segun_periodicidad"
    CHECK (("periodicidad" = 'ANUAL' AND "mesAnual" IS NOT NULL) OR ("periodicidad" = 'MENSUAL' AND "mesAnual" IS NULL));

-- Origin/destination shape per movement kind. Group membership (NEGOCIO vs
-- CASA) depends on another table and is checked by the services.
ALTER TABLE "cn_movimientos"
  ADD CONSTRAINT "cn_movimientos_monto_positivo" CHECK ("monto" > 0),
  ADD CONSTRAINT "cn_movimientos_cuentas_distintas"
    CHECK ("cuentaOrigenId" IS NULL OR "cuentaDestinoId" IS NULL OR "cuentaOrigenId" <> "cuentaDestinoId"),
  ADD CONSTRAINT "cn_movimientos_forma_por_tipo" CHECK (
    CASE "tipo"
      WHEN 'GASTO_NEGOCIO'  THEN "cuentaOrigenId" IS NOT NULL AND "cuentaDestinoId" IS NULL
      WHEN 'APORTE'         THEN "cuentaDestinoId" IS NOT NULL
      WHEN 'RETIRO_CASA'    THEN "cuentaOrigenId" IS NOT NULL AND "cuentaDestinoId" IS NOT NULL
      WHEN 'TRASLADO'       THEN "cuentaOrigenId" IS NOT NULL AND "cuentaDestinoId" IS NOT NULL
      WHEN 'GASTO_FIJO'     THEN "cuentaOrigenId" IS NOT NULL AND "cuentaDestinoId" IS NULL AND "categoriaId" IS NOT NULL
      WHEN 'GASTO_VARIABLE' THEN "cuentaOrigenId" IS NOT NULL AND "cuentaDestinoId" IS NULL AND "categoriaId" IS NOT NULL
      WHEN 'INGRESO_CASA'   THEN "cuentaOrigenId" IS NULL AND "cuentaDestinoId" IS NOT NULL
    END
  ),
  -- Only household expenses carry a category.
  ADD CONSTRAINT "cn_movimientos_categoria_solo_gasto_casa"
    CHECK ("categoriaId" IS NULL OR "tipo" IN ('GASTO_FIJO', 'GASTO_VARIABLE')),
  ADD CONSTRAINT "cn_movimientos_eliminacion_coherente"
    CHECK (("eliminadoEn" IS NULL AND "eliminadoPor" IS NULL) OR ("eliminadoEn" IS NOT NULL AND "eliminadoPor" IS NOT NULL));

-- Exactly one automatic movement per assignment: a payment event or a disbursement.
ALTER TABLE "cn_asignaciones_cuenta"
  ADD CONSTRAINT "cn_asignaciones_cuenta_un_origen" CHECK (num_nonnulls("eventoFinancieroId", "creditoId") = 1);

ALTER TABLE "cn_arqueo_detalles"
  ADD CONSTRAINT "cn_arqueo_detalles_diferencia_cuadra" CHECK ("diferencia" = "contado" - "saldoSistema");

ALTER TABLE "cn_configuracion"
  ADD CONSTRAINT "cn_configuracion_fila_unica" CHECK ("id" = 'default'),
  ADD CONSTRAINT "cn_configuracion_metas_no_negativas"
    CHECK (("metaAsignacionCasa" IS NULL OR "metaAsignacionCasa" >= 0) AND ("metaAhorro" IS NULL OR "metaAhorro" >= 0));

ALTER TABLE "cn_reglas_aviso"
  ADD CONSTRAINT "cn_reglas_aviso_umbral_positivo" CHECK ("umbral" IS NULL OR "umbral" > 0);

ALTER TABLE "cn_castigos_credito"
  ADD CONSTRAINT "cn_castigos_credito_monto_positivo" CHECK ("monto" > 0),
  -- A reversal is all-or-nothing: when, who and why.
  ADD CONSTRAINT "cn_castigos_credito_reversion_completa" CHECK (
    ("revertidoEn" IS NULL AND "revertidoPor" IS NULL AND "motivoReversion" IS NULL)
    OR ("revertidoEn" IS NOT NULL AND "revertidoPor" IS NOT NULL AND "motivoReversion" IS NOT NULL)
  );

