-- Casa y Negocio, v1 (docs/specs/casa-negocio.md).
--
-- Purely additive: seven enums and ten new tables, all prefixed "cn_". No
-- existing column, index, constraint or row is touched. The module links to
-- the loan tables only through FKs that live on its own tables:
--   * cn_asignaciones_cuenta -> eventos_financieros / creditos, ON DELETE
--     CASCADE: an abono reversal deletes its event and the account assignment
--     must go with it instead of blocking the reversal.
--   * cn_castigos_credito -> creditos, ON DELETE RESTRICT: credits are only
--     soft-deleted, so a physical delete of a written-off credit is refused.
--
-- Left out on purpose: the pre-existing drift on
-- "abono_snapshots"."eventosDespues" DEFAULT that `prisma migrate diff`
-- reports against the current schema; it is unrelated to this module.
--
-- Prisma does not model CHECK constraints, so section 3 adds them by hand.
-- Prisma's diff does not introspect CHECKs either, so they cause no drift.
-- They mirror the validation in src/server/casa-negocio/rules.ts and are the
-- last line of defence for scripts and future code paths.
--
-- Section 4 inserts the module defaults (settings row and the ten alert rules
-- of spec section 5) with ON CONFLICT DO NOTHING, so re-running is harmless.
--
-- Locks: only CREATE statements on new objects plus FKs that reference
-- "eventos_financieros", "creditos" and "users" (SHARE ROW EXCLUSIVE on the
-- referenced table for an instant; nothing is rewritten or scanned there).
--
-- Manual rollback (nothing else depends on these objects):
--   DROP TABLE "cn_castigos_credito", "cn_permisos", "cn_reglas_aviso",
--     "cn_configuracion", "cn_arqueo_detalles", "cn_arqueos",
--     "cn_asignaciones_cuenta", "cn_movimientos", "cn_categorias_gasto",
--     "cn_cuentas";
--   DROP TYPE "CnCodigoAviso", "CnCapacidad", "CnPeriodicidad", "CnClaseGasto",
--     "CnTipoMovimiento", "CnTipoCuenta", "CnGrupoCuenta";
--   DELETE FROM "_prisma_migrations" WHERE migration_name = '20261126120000_casa_negocio_v1';

