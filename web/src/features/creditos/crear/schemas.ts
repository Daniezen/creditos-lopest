/**
 * Input schemas for creating a credit from the wizard and for the credit
 * conditions form it shares with the edit screen.
 *
 * The conditions schema validates shape (strings of bounded size, known
 * enums). The numeric meaning of each field (positive amount, positive term,
 * rate normalisation) stays in `normalizarCondicionesCredito`, which runs only
 * when a schedule is actually generated: a notes-only edit of a credit with
 * financial activity must not fail because of its read-only financial fields.
 */
import { z } from "zod";

import { entityId, optionalText } from "@/server/validation/input";

const IDEMPOTENCY_MESSAGE = "No se pudo identificar la operación. Reinicia el flujo e inténtalo de nuevo.";

const FRECUENCIAS = ["Mensual", "Quincenal 15/30", "Quincenal 5/20", "Quincenal 10/25"] as const;
const TIPOS_AMORTIZACION = ["Amortización Fija", "Solo Interés"] as const;

/** Mirrors `SimulatorFormState`; `""` is the form's "nothing selected yet". */
export const condicionesCreditoSchema = z.object({
  fechaPrestamo: z.string({ error: "La fecha del préstamo es obligatoria." }).max(10, "La fecha del préstamo no es válida."),
  monto: z.string({ error: "El valor del préstamo es obligatorio." }).max(32, "El valor del préstamo no es válido."),
  plazoMeses: z.string({ error: "El plazo es obligatorio." }).max(16, "El plazo no es válido."),
  tasaMensual: z.string({ error: "La tasa mensual es obligatoria." }).max(16, "La tasa mensual no es válida."),
  frecuencia: z.enum([...FRECUENCIAS, ""], { error: "La frecuencia de pago no es válida." }),
  tipoAmortizacion: z.enum([...TIPOS_AMORTIZACION, ""], { error: "El tipo de crédito no es válido." }),
});

export const crearCreditoSchema = z.object({
  clienteId: z
    .string({ error: "Selecciona un cliente antes de guardar." })
    .trim()
    .min(1, "Selecciona un cliente antes de guardar.")
    .pipe(entityId("clienteId")),
  form: condicionesCreditoSchema,
  nota: optionalText({ max: 1000, tooLong: "La nota no puede superar 1000 caracteres." }),
  // Generated by the wizard once per flow (crypto.randomUUID); it is the
  // credit's idempotency key, so it must be present and of bounded size.
  idempotencyKey: z
    .string({ error: IDEMPOTENCY_MESSAGE })
    .trim()
    .min(1, IDEMPOTENCY_MESSAGE)
    .max(128, IDEMPOTENCY_MESSAGE),
  confirmarPosibleDuplicado: z.boolean().optional(),
  motivoDuplicado: z.string().max(500, "El motivo no puede superar 500 caracteres.").optional(),
});

export type CrearCreditoInput = z.output<typeof crearCreditoSchema>;
